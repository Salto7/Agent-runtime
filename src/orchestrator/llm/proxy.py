"""Optional LiteLLM OpenAI-compatible proxy lifecycle.

Agent traffic stays in-process (``orchestrator.llm``). This gateway is for
external OpenAI-compatible clients (OpenCode in the Learn lab, the Cognee
sidecar). Intent comes from the ``LLM_PROXY_ENABLED`` setting; ``apply`` starts
or stops the ``litellm`` container (default name ``orchestrator-litellm``).
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from agent_runtime.docker.engine import DockerEngine
from orchestrator import settings
from orchestrator.config import configure, get_config
from orchestrator.utils.service import SharedServiceBase

logger = logging.getLogger(__name__)

def _proxy_config_yaml(model: str) -> str:
    """Single-chat-model proxy config (matches compose litellm entrypoint)."""
    mid = (model or "").strip() or get_config().litellm_model
    # model_name must be a YAML plain/quoted scalar; OpenRouter ids contain '/'.
    return (
        "# Generated by orchestrator when the LLM proxy is enabled.\n"
        "# Chat: LITELLM_MODEL only. Embeddings: OpenRouter text-embedding-3-small.\n"
        "model_list:\n"
        "  - model_name: default\n"
        "    litellm_params:\n"
        "      model: os.environ/LITELLM_MODEL\n"
        "      api_key: os.environ/OPENROUTER_API_KEY\n"
        f"  - model_name: {mid!r}\n"
        "    litellm_params:\n"
        "      model: os.environ/LITELLM_MODEL\n"
        "      api_key: os.environ/OPENROUTER_API_KEY\n"
        "  - model_name: openrouter/openai/text-embedding-3-small\n"
        "    litellm_params:\n"
        "      model: openrouter/openai/text-embedding-3-small\n"
        "      api_key: os.environ/OPENROUTER_API_KEY\n"
        "\n"
        "general_settings:\n"
        "  master_key: os.environ/LITELLM_MASTER_KEY\n"
    )


class LlmProxy(SharedServiceBase):
    """Start/stop the LiteLLM /v1 gateway used by OpenCode."""

    def container_name(self) -> str:
        return settings.get_str("LLM_PROXY_CONTAINER", "orchestrator-litellm")

    def image(self) -> str:
        return settings.get_str("LLM_PROXY_IMAGE", "ghcr.io/berriai/litellm:main-stable")

    def master_key(self) -> str:
        return settings.get_str("LITELLM_MASTER_KEY", "sk-orchestrator-litellm")

    def proxy_url(self) -> str:
        return settings.get_str("LLM_PROXY_URL", "http://localhost:4000/v1")

    def host_port(self) -> int:
        return max(1, settings.get_int("LLM_PROXY_PORT", 4000))

    def config_path(self) -> Path:
        path = Path(get_config().platform_workspace_dir).resolve() / "litellm" / "config.yaml"
        path.parent.mkdir(parents=True, exist_ok=True)
        return path

    @staticmethod
    def intent_enabled() -> bool:
        """Operator intent (``LLM_PROXY_ENABLED`` setting / env)."""
        return settings.get_bool("LLM_PROXY_ENABLED", False)

    def sync_orchestrator(self, *, enabled: bool | None = None) -> None:
        on = self.intent_enabled() if enabled is None else bool(enabled)
        try:
            cfg = get_config()
            configure(cfg.merge(llm_proxy_enabled=on, llm_proxy_url=self.proxy_url()))
        except Exception as exc:
            logger.warning("failed to sync llm proxy flag to orchestrator: %s", exc)

    def apply(self, enabled: bool) -> dict[str, Any]:
        """Honor Settings toggle: start or stop the gateway container."""
        self.sync_orchestrator(enabled=bool(enabled))
        if enabled:
            return self.ensure()
        return self.stop()

    def status(self) -> dict[str, Any]:
        cli = DockerEngine.shared()
        name = self.container_name()
        ok, err = cli.daemon_ok()
        if not ok:
            return {
                "name": name,
                "exists": False,
                "running": False,
                "docker": False,
                "intent": self.intent_enabled(),
                "url": self.proxy_url(),
                "error": (err or "")[:300],
            }
        exists, running = cli.inspect_running(name)
        # Compose may have created a suffixed container name instead.
        if not exists:
            for alt in cli.ps_ids("name=orchestrator-litellm"):
                exists, running = cli.inspect_running(alt)
                if exists:
                    name = alt
                    break
        return {
            "name": name,
            "exists": exists,
            "running": running,
            "docker": True,
            "intent": self.intent_enabled(),
            "url": self.proxy_url(),
            "error": "",
        }

    def snapshot(self) -> dict[str, Any]:
        """Operator-facing view: intent + live container status + URL."""
        st = self.status()
        intent = bool(st.get("intent"))
        return {
            "enabled": intent,
            "running": bool(st.get("running")),
            "url": self.proxy_url() if intent else None,
            "status": st,
        }

    def ensure(self) -> dict[str, Any]:
        cli = DockerEngine.shared()
        cli.require_daemon()
        name = self.container_name()
        exists, running = cli.inspect_running(name)
        if exists and running:
            return {"ok": True, "action": "reused", "proxy": self.status()}
        if exists and not running:
            start = cli.start(name)
            if not start.ok:
                return {
                    "ok": False,
                    "action": "start_failed",
                    "error": (start.stderr or start.stdout or "").strip()[:400],
                    "proxy": self.status(),
                }
            return {"ok": True, "action": "started", "proxy": self.status()}

        config = self.config_path()
        litellm_model = get_config().litellm_model
        # Always refresh so the proxy tracks the single LITELLM_MODEL knob.
        config.write_text(_proxy_config_yaml(litellm_model), encoding="utf-8")
        host_config = cli.host_bind_path(config)
        network = self._compose_network(cli)
        port = self.host_port()
        env = {
            "LITELLM_MODEL": litellm_model,
            "OPENROUTER_API_KEY": settings.get_str("OPENROUTER_API_KEY")
            or get_config().litellm_api_key,
            "LITELLM_API_KEY": get_config().litellm_api_key,
            "LITELLM_MASTER_KEY": self.master_key(),
        }
        create = cli.run_detached(
            name=name,
            image=self.image(),
            workdir="/app",
            network=network,
            network_aliases=["litellm"],
            env=env,
            ports={"4000/tcp": port},
            volumes=[f"{host_config}:/app/config.yaml:ro"],
            labels={"orchestrator.llm_proxy": "1"},
            restart_policy="unless-stopped",
            command=[
                "--config",
                "/app/config.yaml",
                "--host",
                "0.0.0.0",
                "--port",
                "4000",
            ],
        )
        if not create.ok:
            err = (create.stderr or create.stdout or "").strip()
            # Race / name taken by compose service.
            exists2, running2 = cli.inspect_running(name)
            if exists2:
                if not running2:
                    cli.start(name)
                return {"ok": True, "action": "reused", "proxy": self.status()}
            return {
                "ok": False,
                "action": "create_failed",
                "error": err[:500],
                "proxy": self.status(),
            }
        return {"ok": True, "action": "created", "proxy": self.status()}

    def stop(self) -> dict[str, Any]:
        cli = DockerEngine.shared()
        name = self.container_name()
        if not cli.available():
            return {
                "ok": False,
                "removed": False,
                "error": "docker unavailable",
                "proxy": self.status(),
            }
        removed = False
        for ref in [name, *cli.ps_ids("label=orchestrator.llm_proxy=1")]:
            res = cli.rm_force(ref)
            if res.ok:
                removed = True
        return {"ok": True, "removed": removed, "proxy": self.status()}

    def _compose_network(self, cli: DockerEngine) -> str:
        """Network to attach helper containers to: this process's own network when it
        runs in a container, else ``LLM_PROXY_NETWORK`` — but only if it exists
        (``""`` = Docker's default bridge)."""
        preferred = settings.get_str("LLM_PROXY_NETWORK", "orchestrator_default")
        try:
            cid = cli.self_container_id()
            if cid:
                nets = cli.networks(cid)
                if nets:
                    return preferred if preferred in nets else next(iter(nets.keys()))
        except Exception as exc:
            logger.info("compose network probe failed: %s", exc)
        return preferred if self._network_exists(cli, preferred) else ""

    @staticmethod
    def _network_exists(cli: DockerEngine, name: str) -> bool:
        try:
            return any(n.get("Name") == name for n in cli.api.networks(names=[name]))
        except Exception:  # noqa: BLE001 — unknown ⇒ do not attach
            return False
